import { queryOptions } from "@tanstack/react-query";
import { apiBaseUrl } from "@/lib/api/base-url";
import type { PagedEnvelope } from "@/types/paged-envelope";

/**
 * The orders feature's fetch and query keys — the `features/<f>/api.ts` home
 * frontend-architecture §Structure mandates. The server seed calls the list
 * factory too, so it cannot live in a `"use client"` module.
 */

/** GLOSSARY "Sales order": only DRAFT is editable. */
export type OrderStatus =
  | "DRAFT"
  | "CONFIRMED"
  | "PROCESSING"
  | "COMPLETED"
  | "CANCELLED"
  | "RETURNED";

/** One row of the orders table (the API's summary envelope). */
export type OrderSummary = {
  id: number;
  /** ORD-YYYY-NNNN, generated by the server. */
  number: string;
  customerId: number;
  customerName: string;
  status: OrderStatus;
  /** The server's total — never recomputed from the client's own math. */
  total: number;
  createdAt: string;
};

/** One line of the detail (GLOSSARY "Order item"). */
export type OrderItem = {
  id: number;
  productId: number;
  sku: string;
  productName: string;
  quantity: number;
  /** The product's price while the order is a DRAFT, locked at CONFIRM. */
  unitPrice: number;
  subtotal: number;
};

/** The order detail the editor seeds from. */
export type Order = {
  id: number;
  number: string;
  customerId: number;
  customerName: string;
  status: OrderStatus;
  items: OrderItem[];
  total: number;
  createdAt: string;
};

/** One line of the write body: the price comes from the product, not here. */
export type OrderItemBody = { productId: number; quantity: number };

/**
 * The write body create and edit share. PUT replaces the whole draft, so this
 * always carries the complete item set — adding, removing and re-quantifying
 * are the same verb.
 */
export type OrderBody = { customerId: number; items: OrderItemBody[] };

export const ORDERS_KEY = ["orders"] as const;

/** One page of orders, newest first. */
export async function fetchOrders(
  page: number,
  init?: RequestInit,
): Promise<PagedEnvelope<OrderSummary>> {
  const params = new URLSearchParams({ page: String(page) });
  const response = await fetch(
    `${apiBaseUrl()}/api/orders?${params.toString()}`,
    { ...init, credentials: "include" },
  );
  if (!response.ok) {
    throw new Error(`GET /api/orders -> ${response.status}`);
  }
  return (await response.json()) as PagedEnvelope<OrderSummary>;
}

/** The list's one query definition: the key carries the page (ADR 0019/0020). */
export function ordersQuery(page: number, init?: RequestInit) {
  return queryOptions({
    queryKey: [...ORDERS_KEY, page],
    queryFn: () => fetchOrders(page, init),
  });
}

/** The detail, including the lines the editor seeds its fields from. */
export async function fetchOrder(
  id: number,
  init?: RequestInit,
): Promise<Order> {
  const response = await fetch(`${apiBaseUrl()}/api/orders/${id}`, {
    ...init,
    credentials: "include",
  });
  if (!response.ok) {
    throw new Error(`GET /api/orders/${id} -> ${response.status}`);
  }
  return (await response.json()) as Order;
}

export function orderQuery(id: number, init?: RequestInit) {
  return queryOptions({
    queryKey: [...ORDERS_KEY, "detail", id],
    queryFn: () => fetchOrder(id, init),
  });
}
